-- 1. إنشاء جدول الخدمات (Services)
CREATE TABLE public.services (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    name TEXT NOT NULL UNIQUE, -- الاسم البرمجي (مثل: plumbing)
    label TEXT NOT NULL, -- الاسم المعروض (مثل: سباكة)
    category TEXT NOT NULL, -- التصنيف (صيانة منزلية، تبريد، أجهزة)
    icon TEXT, -- الرمز التعبيري (Emoji) كنسخة احتياطية
    image_url TEXT, -- رابط الصورة في Storage
    price_range TEXT, -- نطاق السعر (مثل: 100 - 200 ج.م)
    is_emergency_supported BOOLEAN DEFAULT false,
    keywords TEXT[] DEFAULT '{}', -- مصفوفة الكلمات المفتاحية للبحث
    is_active BOOLEAN DEFAULT true, -- للتحكم في ظهور الخدمة
    created_at TIMESTAMP WITH TIME ZONE DEFAULT NOW()
);

-- 2. إعداد صلاحيات القراءة للجميع (RLS)
ALTER TABLE public.services ENABLE ROW LEVEL SECURITY;

CREATE POLICY "Allow public read access on services" 
ON public.services FOR SELECT 
TO public 
USING (true);

-- 3. صلاحيات التعديل للأدمن فقط (يمكن تخصيصها لاحقاً)
CREATE POLICY "Allow admin all access on services" 
ON public.services FOR ALL 
TO authenticated 
USING (true);

